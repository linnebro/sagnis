#!/usr/bin/env python3
"""One canonical instruction file, generated per-tool pointer files. Stdlib only.

    python build_shims.py <dir>                      # write CLAUDE.md (+ others) beside <dir>/AGENTS.md
    python build_shims.py <dir> --tools claude,gemini
    python build_shims.py <dir> --check              # exit 1 if a shim is missing or differs
    python build_shims.py --selftest

The canonical file is `AGENTS.md` (the Agentic AI Foundation convention, which
several assistants read natively; check yours). A tool that only reads its own file
name gets a generated shim that imports or points at AGENTS.md:

  claude   CLAUDE.md                  `@AGENTS.md` (import; also keeps older Claude Code
                                      versions, and any CLAUDE.md higher up the tree, working)
  gemini   GEMINI.md                  `@AGENTS.md` (Gemini CLI import syntax; untested here)
  copilot  .github/copilot-instructions.md   plain pointer (no import syntax)

Shims carry the generated header, so a hand edit to a shim is caught by --check and
by health_check.py; the content belongs in AGENTS.md. Imports written in Claude's
`@path` form inside AGENTS.md are honored by Claude Code and read as a literal
pointer by tools without imports: enforced there, best-effort elsewhere, the same
split as hooks.
"""
import argparse
import sys
import tempfile
from pathlib import Path

HEADER = "<!-- generated by build_shims.py; the instructions live in AGENTS.md. Hand edits are overwritten. -->"
SHIMS = {
    "claude": ("CLAUDE.md", HEADER + "\n@AGENTS.md\n"),
    "gemini": ("GEMINI.md", HEADER + "\n@AGENTS.md\n"),
    "copilot": (".github/copilot-instructions.md",
                HEADER + "\nRead `AGENTS.md` at the repository root first; it is the instruction file for this repository.\n"),
}
DEFAULT_TOOLS = ["claude"]


def wanted(root, tools):
    """-> {path: text} for the shims this directory should carry."""
    root = Path(root)
    return {root / SHIMS[t][0]: SHIMS[t][1] for t in tools}


def check(root, tools):
    """-> [(path, 'missing'|'differs')] ; an AGENTS.md that is absent is reported first."""
    root = Path(root)
    out = []
    if not (root / "AGENTS.md").is_file():
        out.append((root / "AGENTS.md", "missing"))
    for p, text in wanted(root, tools).items():
        if not p.is_file():
            out.append((p, "missing"))
        elif p.read_text(encoding="utf-8") != text:
            out.append((p, "differs"))
    return out


def write(root, tools):
    """Write every shim; refuses to overwrite a hand-written file (no header). -> [(path, status)]"""
    out = []
    for p, text in wanted(root, tools).items():
        if p.is_file():
            old = p.read_text(encoding="utf-8")
            if old == text:
                out.append((p, "ok"))
                continue
            if not old.startswith(HEADER):
                out.append((p, "kept (hand-written; move its content into AGENTS.md, then rerun)"))
                continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        out.append((p, "written"))
    return out


def selftest():
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        assert check(d, ["claude"]) == [(d / "AGENTS.md", "missing"), (d / "CLAUDE.md", "missing")]
        (d / "AGENTS.md").write_text("# rules\n", encoding="utf-8")
        assert write(d, ["claude", "gemini", "copilot"]) == [
            (d / "CLAUDE.md", "written"), (d / "GEMINI.md", "written"),
            (d / ".github" / "copilot-instructions.md", "written")]
        assert (d / "CLAUDE.md").read_text(encoding="utf-8") == HEADER + "\n@AGENTS.md\n"
        assert check(d, ["claude", "gemini", "copilot"]) == []
        assert write(d, ["claude"]) == [(d / "CLAUDE.md", "ok")]                       # idempotent
        (d / "CLAUDE.md").write_text(HEADER + "\n@AGENTS.md\nextra\n", encoding="utf-8")
        assert check(d, ["claude"]) == [(d / "CLAUDE.md", "differs")]
        assert write(d, ["claude"]) == [(d / "CLAUDE.md", "written")]                  # generated: rewritten
        (d / "GEMINI.md").write_text("# my own gemini rules\n", encoding="utf-8")
        assert write(d, ["gemini"])[0][1].startswith("kept (hand-written")             # hand-written: refused
    print("selftest ok")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dir", nargs="?", help="folder holding AGENTS.md")
    ap.add_argument("--tools", default=",".join(DEFAULT_TOOLS), help="comma list of " + ", ".join(SHIMS))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if not a.dir:
        ap.error("dir is required")
    tools = [t.strip() for t in a.tools.split(",") if t.strip()]
    bad = [t for t in tools if t not in SHIMS]
    if bad:
        ap.error(f"unknown tool(s): {', '.join(bad)}; known: {', '.join(SHIMS)}")
    if a.check:
        drift = check(a.dir, tools)
        for p, st in drift:
            print(f"{st:8s} {p}")
        print("shims match AGENTS.md" if not drift else f"{len(drift)} shim(s) need attention; run without --check")
        return 1 if drift else 0
    if not (Path(a.dir) / "AGENTS.md").is_file():
        print(f"no AGENTS.md in {a.dir}: rename the instruction file to AGENTS.md first", file=sys.stderr)
        return 1
    for p, st in write(a.dir, tools):
        print(f"{st:8s} {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
